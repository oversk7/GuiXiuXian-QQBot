// 手工/CI 浏览器回归：先构建 HTML，再以 NODE_PATH 指向安装了 playwright 的目录运行。
const {chromium} = require('playwright');
const {pathToFileURL} = require('node:url');
const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async()=>{
    const browser = await chromium.launch({channel:'chrome',headless:true});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1000}});
    const errors=[]; page.on('pageerror',e=>errors.push(e.message));
    const network=[]; page.on('request',r=>{if(/^https?:/.test(r.url()))network.push(r.url());});
    await page.goto(pathToFileURL(path.resolve('plugins/xiuxian_game/story/story_debugger.html')).href);
    await page.locator('#demo').click();
    await page.locator('#choices button').first().click();
    assert.equal(await page.locator('#current-id').textContent(),'door');
    await page.locator('#choices button').nth(1).click();
    assert.equal(await page.locator('#current-id').textContent(),'inside');
    await page.locator('#choices button').first().click();
    assert.equal(await page.locator('#current-id').textContent(),'reward');
    await page.locator('#choices button').first().click();
    assert.equal(await page.locator('#current-id').textContent(),'perfect');
    assert.match(await page.locator('#completed').textContent(),/雾中来信_完美/);
    await page.locator('#undo').click();
    assert.equal(await page.locator('#current-id').textContent(),'reward');
    assert.doesNotMatch(await page.locator('#completed').textContent(),/雾中来信_完美/);
    await page.locator('#restart').click();
    await page.locator('#edit-player').click();
    await page.locator('#fields input[data-key="gold"]').fill('0');
    await page.locator('#fields input[data-key="fenjin_charge"]').fill('0.5');
    await page.locator('#editor-form button[type="submit"]').click();
    await page.locator('#choices button').first().click();
    assert.equal(await page.locator('#choices button').count(),2);
    await page.locator('#show-hidden').check();
    assert.equal(await page.locator('#choices button:disabled').count(),1);
    await page.locator('#edit-vars').click();
    await page.locator('#json-editor').fill(JSON.stringify({current_story_id:'雾中来信',has_letter:false,courage:0}));
    await page.locator('#editor-form button[type="submit"]').click();
    assert.equal(await page.locator('#choices button:disabled').count(),2);
    const downloadPromise = page.waitForEvent('download'); await page.locator('#export').click();
    const download = await downloadPromise; assert.equal(download.suggestedFilename(),'试炼调试记录.json');
    const report = JSON.parse(fs.readFileSync(await download.path(),'utf8')); assert.equal(report.current.nodeId,'door');
    assert.equal(report.current.player.fenjin_charge,0.5);
    await page.locator('#nodes button').filter({hasText:'perfect'}).click();
    assert.equal(await page.locator('#current-id').textContent(),'perfect');
    await page.locator('#undo').click();
    assert.equal(await page.locator('#current-id').textContent(),'door');
    await page.locator('#paste').click();
    const storyDownload = page.waitForEvent('download'); await page.locator('#download-story').click();
    const savedStory = JSON.parse(fs.readFileSync(await (await storyDownload).path(),'utf8')); assert.equal(savedStory.id,'雾中来信');
    await page.locator('#cancel-editor').click();
    for(const file of fs.readdirSync('plugins/xiuxian_game/data/stories').filter(f=>f.endsWith('.json'))){
      await page.locator('#file').setInputFiles(path.resolve('plugins/xiuxian_game/data/stories',file));
      assert.equal(await page.locator('#play').isVisible(),true,`${file} should load`);
    }
    await page.locator('#file').setInputFiles({name:'broken.json',mimeType:'application/json',buffer:Buffer.from('{"id":"bad","start_node":"x","nodes":{"x":[]}}')});
    assert.equal(await page.locator('#invalid').isVisible(),true);
    assert.ok(await page.locator('.issue.error').count()>0);
    await page.locator('#paste').click();
    await page.locator('#json-editor').fill('{broken');
    await page.locator('#editor-form button[type="submit"]').click();
    assert.ok(await page.locator('#editor-error').textContent());
    await page.locator('#cancel-editor').click();
    const hostile={id:'safe',title:'<img src=x onerror=alert(1)>',start_node:'x',nodes:{x:{type:'end',content:'<script>window.HACKED=true</script>'}}};
    await page.locator('#file').setInputFiles({name:'safe.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(hostile))});
    assert.equal(await page.evaluate(()=>window.HACKED),undefined);
    assert.equal(await page.locator('#title img').count(),0);
    await page.locator('#file').setInputFiles({name:'null.json',mimeType:'application/json',buffer:Buffer.from('null')});
    assert.equal(await page.locator('#invalid').isVisible(),true);
    const stuck={id:'stuck',start_node:'s',nodes:{s:{type:'story',content:'未匹配路由',effects:{player:{gold:'+5'}},next:[{if:{player_gold:{'>':9999}},goto:'e'}]},e:{type:'end',content:'结局'}}};
    await page.locator('#file').setInputFiles({name:'stuck.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(stuck))});
    await page.locator('#choices button').click();
    assert.equal(await page.locator('#current-id').textContent(),'s');
    assert.match(await page.locator('#notice').textContent(),/效果已应用/);
    assert.match(await page.locator('#trace').textContent(),/gold/);
    await page.locator('#undo').click();
    await page.reload(); await page.locator('#demo').click(); await page.locator('#choices button').first().click();
    await page.screenshot({path:path.join(require('node:os').tmpdir(),'story-workshop-desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile horizontal overflow');
    await page.locator('#edit-player').click();
    assert.equal(await page.locator('#editor').isVisible(),true); await page.locator('#cancel-editor').click();
    await page.screenshot({path:path.join(require('node:os').tmpdir(),'story-workshop-mobile.png'),fullPage:true});
    assert.deepEqual(errors,[]); assert.deepEqual(network,[]);
    console.log('PASS: demo endings/undo/restart, player/variable edits, locked choices, export, all shipped JSON files, malformed input, text injection, offline requests, mobile layout.');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
