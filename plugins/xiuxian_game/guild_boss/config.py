# ==================== 血量公式 ====================
# HP = Σ(成员有效攻击力) × HP_FACTOR × D(凶戾度)
# HP_FACTOR = 预估单场有效回合数15 × 目标出力系数1.8（3次×60%参与率）
# 上线后按真实战斗日志校准 HP_FACTOR
HP_FACTOR = 27


def ferocity_multiplier(level: int) -> float:
    """凶戾度倍率 D(lv) = 1 + 0.08 × (lv - 1)"""
    return 1 + 0.08 * (max(1, level) - 1)


