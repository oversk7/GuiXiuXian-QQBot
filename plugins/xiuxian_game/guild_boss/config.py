# ==================== 血量公式 ====================
# HP = Σ(活跃成员有效攻击力) × HP_FACTOR × D(凶戾度)
# 初版27（15回合×1.8出力系数），2026-07生产实测最强者两三次出手即镇压完毕，
# 翻倍至54，要求多名成员合力才能在时限内镇住
