empty_at_cmd = on_message(rule=to_me(), priority=99, block=True)
@empty_at_cmd.handle()
async def handle_empty_at(event: MessageEvent):
    """用户仅@机器人不说话时，等同于触发帮助"""
    text = event.get_plaintext().strip()
    if text:
        return
    await handle_help(event, Message())

